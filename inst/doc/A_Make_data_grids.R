# Create plot using the interaction of both groups
plot_res <- function(data, doBuild=F, doExtract=F, doTotal=F, asSpeedup=F, doLegend=F) {

  data_null = subset(data, data$t == -999)
  data = subset(data, data$t != -999)
  groups <- unique(data$x)
  colors <- palette.colors(length(groups))

  if (doBuild){
    yname = 'build'
    ylbl = 'Build'
  } else if (doExtract) {
    yname = 'extract'
    ylbl = 'Extract'
  } else if (doTotal) {
    yname = 'total'
    ylbl = 'Total'
  }


  if (asSpeedup) {
    ylbl = paste(ylbl, "time speed-up")
    data[, yname] = mean(data_null[, yname]) / data[, yname]
  } else {
    ylbl = paste(ylbl, "time [sec/year]")
  }

  plot(data$t, data[, yname],
       type = "n",
       xlab = "Time dimesion chunk [days]",
       ylab = ylbl)
  for (i in seq_along(groups)) {
    sub_data <- subset(data, data$x == groups[i])

    sub_data <-  aggregate(as.formula(paste(yname, '~ t')), data = sub_data, FUN = mean)

    lines(sub_data$t, sub_data[, yname], col = colors[i], type = "b", pch = 16)
  }
  if (doLegend)
    legend("topright", legend = groups, col = colors, lty = 1, pch = 16, title = 'Spatial chunk [cells]')
}

